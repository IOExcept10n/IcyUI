namespace Icy.UI
{
    /// <summary>
    /// Specifies where each line of text sits within the width of the element that shows it.
    /// </summary>
    public enum TextAlignment
    {
        /// <summary>
        /// Every line starts at the left edge.
        /// </summary>
        Left,

        /// <summary>
        /// Every line is centered.
        /// </summary>
        Center,

        /// <summary>
        /// Every line ends at the right edge.
        /// </summary>
        Right,
    }
}
